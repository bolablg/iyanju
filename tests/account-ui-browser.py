"""Synthetic session interaction and central adapter checks. Never calls real Clerk."""
import json
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT = Path.cwd()
OUT = ROOT / "test-results"
BASE = os.environ.get("IYANJU_ACCOUNT_UI_TEST_URL", "http://127.0.0.1:43127")
summary = {"version": 1, "services": [
    {"serviceId": "kazi", "state": "activated", "activation": {"activatedAt": None, "firstObservedAt": 1800000000000}},
    {"serviceId": "wlan", "state": "unavailable"},
    {"serviceId": "playkin", "state": "not_activated"},
]}
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    context = browser.new_context(viewport={"width": 1440, "height": 1000}, reduced_motion="reduce")
    page = context.new_page()
    page.set_default_timeout(30000)
    page.set_default_navigation_timeout(60000)
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.route("**/account/services", lambda route: route.fulfill(json=summary))
    page.route("**/missing-avatar.png", lambda route: route.fulfill(status=404, body="missing"))
    page.goto(BASE)
    page.wait_for_load_state("networkidle")
    page.evaluate("document.fonts.ready")
    trigger = page.locator(".hostile-app .iy-trigger")
    popup = page.get_by_role("menu", name="iYANJU account", exact=True)
    trigger.focus()
    page.keyboard.press("ArrowDown")
    profile = popup.get_by_role("menuitem", name="Profile & security")
    expect(profile).to_be_focused()
    expect(profile).to_have_attribute("href", "/account?view=profile")
    expect(popup.get_by_role("menuitem", name="Your services")).to_have_attribute("href", "/account")
    assert popup.get_by_role("menuitem").all_text_contents() == ["Profile & security", "Your services", "Settings", "Connections", "Invite teammate", "Admin settings", "Sign out"]
    expect(popup.get_by_text("Example role: Editor")).to_be_visible()
    page.keyboard.press("ArrowDown")
    expect(popup.get_by_role("menuitem", name="Your services")).to_be_focused()
    page.keyboard.press("End")
    expect(popup.get_by_role("menuitem", name="Sign out", exact=True)).to_be_focused()
    page.keyboard.press("ArrowUp")
    expect(popup.get_by_role("menuitem", name="Invite teammate")).to_be_focused()
    page.keyboard.press("ArrowUp")
    expect(popup.get_by_role("menuitem", name="Connections")).to_be_focused()
    page.keyboard.press("Home")
    expect(profile).to_be_focused()
    page.keyboard.press("s")
    expect(popup.get_by_role("menuitem", name="Settings", exact=True)).to_be_focused()
    page.keyboard.press("Escape")
    expect(trigger).to_be_focused()
    expect(popup).to_have_count(0)
    page.keyboard.press("ArrowUp")
    expect(popup.get_by_role("menuitem", name="Sign out", exact=True)).to_be_focused()
    page.keyboard.press("Tab")
    expect(page.get_by_role("link", name="After menu")).to_be_focused()
    trigger.click()
    page.get_by_role("heading", name="Shared account verification").click()
    expect(popup).to_have_count(0)
    trigger.click()
    popup.get_by_role("menuitem", name="Connections").click()
    expect(page.locator(".iy-popover").get_by_role("alert")).to_have_text("We couldn’t open that setting. Please try again.")
    page.get_by_role("button", name="Action failure: on").click()
    trigger.click()
    popup.get_by_role("menuitem", name="Connections").click()
    expect(popup).to_have_count(0)
    expect(page.get_by_label("Service actions")).to_have_text("2")
    trigger.click()
    popup.get_by_role("menuitem", name="Invite teammate").click()
    expect(page.get_by_role("dialog", name="Invite teammate").get_by_label("Invite email")).to_be_focused()
    page.get_by_role("button", name="Close invitation").click()
    trigger.click()
    popup.get_by_role("menuitem", name="Settings", exact=True).click()
    expect(page).to_have_url(BASE + "/settings")
    expect(page.get_by_role("heading", name="Example settings")).to_be_visible()
    page.goto(BASE)
    page.wait_for_load_state("networkidle")
    trigger.click()
    popup.get_by_role("menuitem", name="Sign out", exact=True).evaluate("button => { button.click(); button.click(); }")
    expect(page.get_by_label("Signout attempts")).to_have_text("1")
    expect(popup.get_by_role("menuitem", name="Signing out…")).to_be_disabled()
    expect(page.locator(".iy-popover").get_by_role("alert")).to_have_text("We couldn’t sign you out. Please try again.")
    expect(popup.get_by_role("menuitem", name="Sign out", exact=True)).to_be_enabled()
    page.get_by_role("button", name="Signout failure: on").click()
    trigger.click()
    popup.get_by_role("menuitem", name="Sign out", exact=True).click()
    expect(page.locator(".hostile-app").get_by_role("link", name="Sign in", exact=True)).to_be_focused()
    expect(page.get_by_label("Signout attempts")).to_have_text("2")
    expect(page.locator(".hostile-app")).not_to_contain_text("Ada Example")
    expect(page.locator(".hostile-app [role='menuitem']")).to_have_count(0)
    page.get_by_role("button", name="Signed out fixture").click()
    expect(page.locator(".hostile-app").get_by_role("link", name="Create account")).to_have_attribute("href", "/account/sign-up")
    page.screenshot(path=str(OUT / "shared-account-signed-out.png"), full_page=True)
    page.get_by_role("button", name="Loading fixture").click()
    expect(page.locator(".hostile-app")).to_have_text("Loading your account…")
    page.get_by_role("button", name="Unavailable fixture").click()
    page.locator(".hostile-app").get_by_role("button", name="Try again").click()
    expect(trigger).to_have_attribute("aria-label", "iYANJU account: Ada Example")
    page.get_by_role("button", name="Legacy fixture").click()
    page.locator(".hostile-app .iy-trigger").click()
    legacy = page.get_by_role("menu", name="Legacy Example account")
    expect(legacy).not_to_contain_text("iYANJU account")
    expect(legacy.get_by_role("menuitem", name="Profile & security")).to_have_count(0)
    page.keyboard.press("Escape")
    page.get_by_role("button", name="Shared session").click()
    # The real central adapter preserves activation state and environment-safe launch URLs.
    central = page.locator(".fixture-dashboard")
    expect(central.get_by_text("First-use date unknown")).to_be_visible()
    expect(central.get_by_text("Some service checks are unavailable.")).to_be_visible()
    expect(central.get_by_role("link", name="Open Kazi")).to_have_count(0)
    page.goto(BASE + "/account?view=profile")
    expect(central.get_by_text("These settings apply to your shared iYANJU account.")).to_be_visible()
    expect(central.get_by_role("heading", name="Profile settings fixture")).to_be_visible()
    assert "iYANJU Account" in central.locator(".cl-rootBox h3").evaluate("element => getComputedStyle(element).fontFamily")
    page.goto(BASE)
    page.wait_for_load_state("networkidle")
    for width in [320, 390, 768, 1440]:
        page.set_viewport_size({"width": width, "height": 1000})
        trigger.click()
        page.evaluate("document.fonts.ready")
        assert page.evaluate("document.documentElement.scrollWidth <= innerWidth"), width
        box = popup.bounding_box()
        assert box["x"] >= 0 and box["x"] + box["width"] <= width and box["y"] >= 0, (width, box)
        assert all(item["height"] >= 44 for item in popup.get_by_role("menuitem").evaluate_all("elements => elements.map(e => ({height:e.getBoundingClientRect().height}))"))
        assert "iYANJU Account" in trigger.evaluate("e=>getComputedStyle(e).fontFamily")
        assert trigger.evaluate("e=>getComputedStyle(e).borderRadius") == "0px"
        assert trigger.evaluate("e=>getComputedStyle(e).color") == "rgb(24, 24, 27)"
        assert popup.locator(".iy-icon").first.evaluate("e=>e.getBBox().width > 0"), "Scoped resets must preserve SVG geometry"
        expect(trigger.locator(".iy-avatar")).to_have_text("AE")
        page.add_script_tag(path=str(ROOT / "node_modules/axe-core/axe.min.js"))
        violations = page.evaluate("async()=> (await axe.run(document.querySelector('.iy-popover'),{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa','wcag22aa']}})).violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>({target:n.target,reason:n.failureSummary}))}))")
        assert not violations, violations
        if width in [390, 1440]: page.screenshot(path=str(OUT / f"shared-account-menu-{width}.png"), full_page=True)
        page.keyboard.press("Escape")
    trigger.focus()
    page.keyboard.press("ArrowDown")
    page.keyboard.press("Space")
    expect(page).to_have_url(BASE + "/account?view=profile")
    # Display metadata must use each service's actual brand without changing access state.
    summary["services"] = [{"serviceId": service, "state": "activated", "activation": {"activatedAt": None, "firstObservedAt": 1800000000000}} for service in ["kazi", "wlan", "playkin"]]
    for width in [390, 1440]:
        page.set_viewport_size({"width": width, "height": 1000})
        page.goto(BASE + "/account")
        expect(central.locator(".account-service-list > li")).to_have_count(3)
        page.wait_for_function("Array.from(document.querySelectorAll('.account-service-mark img')).length === 3 && Array.from(document.querySelectorAll('.account-service-mark img')).every(image => image.complete && image.naturalWidth > 0)")
        for asset in ["kazi-logo.svg", "wlan-wordmark.svg", "playkin-mark.png"]:
            expect(central.locator(f'.account-service-mark img[src*="{asset}"]')).to_have_count(1)
        for image in central.locator(".account-service-mark img").all():
            assert image.evaluate("e => { const a=e.getBoundingClientRect(), b=e.parentElement.getBoundingClientRect(); return a.width>0 && a.height>0 && a.width<=b.width && a.height<=b.height; }")
        assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
        page.screenshot(path=str(OUT / f"services-logos-{width}.png"), full_page=True)
    assert not errors, errors
    (OUT / "shared-account-browser-report.json").write_text(json.dumps({"syntheticIdentity": True, "realAccountChanged": False, "checks": ["keyboard", "outside", "service callbacks", "signout duplicate/pending/failure/retry/success", "loading", "signed-out", "legacy", "unavailable/retry", "central services/profile", "font isolation", "mobile", "axe"]}, indent=2))
    context.close()
    browser.close()
    print("PASS: shared menu interactions, synthetic signed-in/out routes, central adapter boundaries, responsive/font isolation and axe checks.")
